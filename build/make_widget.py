"""Turn src/widget.html into:
  public/widget.js                    — self-mounting script (CSS + markup + logic) loaded by Squarespace
  public/index.html                   — test page on the Cloudflare URL
  embed/squarespace-code-block.html   — paste into a Squarespace Code Block
"""
import os, re, json, html
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
SITE = os.environ.get('BPS_SITE_URL', 'https://bogman-pygmy-habitat.bogman-plantenstein.workers.dev/')   # Cloudflare Pages URL

src = open(os.path.join(ROOT, 'src', 'widget.html')).read()
markup = src.split('<style>')[0].strip()
css = re.search(r'<style>([\s\S]*?)</style>', src).group(1).strip()
script = re.search(r'<script>([\s\S]*?)</script>', src).group(1)
inner = re.search(r'<div class="bps" id="bps-root">([\s\S]*)</div>\s*$', markup).group(1).strip()

head = """/* Bogman Plantenstein — Pygmy Sundew Habitat Finder
   Copyright (c) 2026 Bogman Plantenstein LLC. All rights reserved. Generated by build/make_widget.py — edit src/widget.html. */
(function(){
  var CSS = %s;
  var MARKUP = %s;
  var cur = document.currentScript;
  window.BPS_BASE = (cur && cur.src) ? cur.src.replace(/[^\\/?#]*([?#].*)?$/, "") : "";
  if(!document.getElementById("bps-font")){
    var lk = document.createElement("link"); lk.id = "bps-font"; lk.rel = "stylesheet";
    lk.href = "https://fonts.googleapis.com/css2?family=Lora:ital,wght@0,600;1,500;1,600&display=swap"; document.head.appendChild(lk);
  }
  if(!document.getElementById("bps-style")){
    var st = document.createElement("style"); st.id = "bps-style"; st.textContent = CSS; document.head.appendChild(st);
  }
  window.BPS_PREP = function(root){
    if(!root.querySelector("#bps-q")){ root.classList.add("bps"); root.innerHTML = MARKUP; }
  };
})();
""" % (json.dumps(css), json.dumps(inner))
open(os.path.join(ROOT, 'public', 'widget.js'), 'w').write(head + script)

# Plain-text species list for search engines (and for visitors without JavaScript).
D = json.load(open(os.path.join(ROOT, 'public', 'pygmy-data.json')))
order = {'Dry': 0, 'Drained': 1, 'Moist': 2, 'Wet': 3}
rows = []
for t in sorted(D['taxa'], key=lambda t: (order[t['band']], t['hyb'], t['name'])):
    extra = ''
    rows.append('    <li><i>%s</i> — %s soil. %s%s</li>' % (html.escape(t['name']), t['band'].lower(), html.escape(t['hab']), extra))
seo = ('<details class="bps-seo">\n  <summary>All pygmy sundews by soil moisture (text list)</summary>\n  <ul>\n'
       + '\n'.join(rows) + '\n  </ul>\n</details>')

snippet = """<!-- Bogman Pygmy Sundew Habitat Finder. Paste into a Squarespace Code Block (HTML mode). -->
<div id="bps-root"></div>
<script src="%swidget.js" defer></script>
<style>.bps-seo{margin-top:12px;font-size:13px;color:#b9b3a6}.bps-seo summary{cursor:pointer}.bps-seo ul{padding-left:18px}</style>
%s
""" % (SITE, seo)
os.makedirs(os.path.join(ROOT, 'embed'), exist_ok=True)
open(os.path.join(ROOT, 'embed', 'squarespace-code-block.html'), 'w').write(snippet)

test = """<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Pygmy Sundew Habitat Finder — test page</title><meta name="robots" content="noindex">
<style>body{font-family:system-ui,sans-serif;max-width:1100px;margin:24px auto;padding:0 16px;background:#38383b;color:#fff}</style></head>
<body><h1 style="font-size:20px">Pygmy Sundew Habitat Finder (test page)</h1>
<div id="bps-root"></div><script src="widget.js"></script></body></html>
"""
open(os.path.join(ROOT, 'public', 'index.html'), 'w').write(test)
print('widget.js %d KB, data %d KB, code block %d KB' % (
    os.path.getsize(os.path.join(ROOT, 'public', 'widget.js')) // 1024,
    os.path.getsize(os.path.join(ROOT, 'public', 'pygmy-data.json')) // 1024,
    len(snippet) // 1024))
